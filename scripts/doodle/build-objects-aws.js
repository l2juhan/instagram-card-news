'use strict';

/**
 * aws 테마 전용 낙서 오브젝트 확장 세트. build-objects.js(공통 17종, sprite.svg)와 별도
 * 파일(assets/doodle/objects/sprite-aws.svg)로 굽는다 — 공통 스프라이트에 합치면
 * cs-doodle 템플릿에 인라인되는 스프라이트 마크업이 바뀌어서 바이트 동일성이 깨지기
 * 때문이다(scripts/doodle/inline.js의 objectSpriteMarkup 참고).
 *
 * 전부 일반적인 사물로 새로 그린 원작이며, AWS 공식 아이콘의 모양·구도를 참고하지
 * 않았다. 서비스 정체성은 호출부의 서비스명 라벨(Pretendard 텍스트)로 전달한다.
 *
 *   node scripts/doodle/build-objects-aws.js
 */
const fs = require('fs');
const path = require('path');
const R = require('./rough-svg.js');
const PEN = require('./pen-style.js');

const OUT = path.join(__dirname, '..', '..', 'assets', 'doodle', 'objects', 'sprite-aws.svg');

const outline = (seed) => ({ seed, roughness: PEN.roughness, bowing: PEN.bowing, stroke: 'currentColor', strokeWidth: PEN.strokeWidth });

const OBJECTS = {
  'aws-user': (s) => `
    ${R.circle(60, 38, 40, outline(s))}
    ${R.arc(60, 118, 96, 76, Math.PI, 2 * Math.PI, false, outline(s + 1))}
  `,
  'aws-globe': (s) => `
    ${R.circle(60, 60, 92, outline(s))}
    ${R.ellipse(60, 60, 92, 40, outline(s + 1))}
    ${R.line(14, 60, 106, 60, outline(s + 2))}
  `,
  'aws-instance': (s) => `
    ${R.rectangle(28, 28, 64, 64, outline(s))}
    ${R.rectangle(44, 44, 32, 32, outline(s + 1))}
    ${R.line(10, 40, 28, 40, outline(s + 2))}${R.line(10, 80, 28, 80, outline(s + 3))}
    ${R.line(92, 40, 110, 40, outline(s + 4))}${R.line(92, 80, 110, 80, outline(s + 5))}
  `,
  'aws-bucket': (s) => `
    ${R.linearPath([[26, 30], [94, 30], [84, 102], [36, 102], [26, 30]], outline(s))}
    ${R.line(30, 30, 90, 30, outline(s + 1))}
  `,
  'aws-loadbalancer': (s) => `
    ${R.circle(60, 24, 16, outline(s))}
    ${R.line(60, 32, 60, 56, outline(s + 1))}
    ${R.line(60, 56, 26, 90, outline(s + 2))}
    ${R.line(60, 56, 94, 90, outline(s + 3))}
    ${R.circle(26, 98, 12, outline(s + 4))}${R.circle(94, 98, 12, outline(s + 5))}
  `,
  'aws-function': (s) => R.path('M34 20 L60 60 L34 100 M54 60 L92 100', outline(s)),
  'aws-queue': (s) => `
    ${R.rectangle(20, 30, 60, 56, outline(s))}
    ${R.rectangle(34, 44, 60, 56, outline(s + 1))}
    ${R.line(44, 58, 78, 58, outline(s + 2))}${R.line(44, 74, 78, 74, outline(s + 3))}
  `,
  'aws-cdn': (s) => `
    ${R.circle(56, 56, 84, outline(s))}
    ${R.ellipse(56, 56, 84, 36, outline(s + 1))}
    ${R.path('M70 30 L52 62 L66 62 L48 96', outline(s + 2))}
  `,
  'aws-shield': (s) => `
    ${R.linearPath([[60, 14], [102, 30], [102, 62], [60, 108], [18, 62], [18, 30], [60, 14]], outline(s))}
    ${R.path('M40 58 L54 74 L84 40', outline(s + 1))}
  `,
  'aws-gateway': (s) => `
    ${R.arc(60, 60, 76, 92, Math.PI, 2 * Math.PI, false, outline(s))}
    ${R.line(22, 60, 22, 106, outline(s + 1))}${R.line(98, 60, 98, 106, outline(s + 2))}
    ${R.line(14, 106, 106, 106, outline(s + 3))}
    ${R.line(60, 60, 60, 106, outline(s + 4))}
  `,
};

function main() {
  const symbols = Object.entries(OBJECTS)
    .map(([name, draw], i) => `  <symbol id="doodle-${name}" viewBox="0 0 120 120">${draw(i * 20 + 1)}</symbol>`)
    .join('\n');
  const svg = `<!-- GENERATED by scripts/doodle/build-objects-aws.js: 직접 고치지 말고 빌더를 수정한 뒤 다시 생성할 것 -->\n<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">\n${symbols}\n</svg>\n`;
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, svg);
  console.log(`aws: ${Object.keys(OBJECTS).length} object symbols written to ${OUT}`);
}

if (require.main === module) main();

module.exports = { OBJECTS };
